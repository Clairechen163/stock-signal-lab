"""Rewrite the live section of README.md from the latest run.

Only the text between the LIVE markers is replaced, so everything else in the README
(the story, methods and the dated original study) stays exactly as written.
"""

from __future__ import annotations

import os

import pandas as pd

from .board import ACTIONS, why

START = "<!-- LIVE:START (generated by `python -m stocklab update`; edits here are overwritten) -->"
END = "<!-- LIVE:END -->"
PM_START = "<!-- PREMARKET:START (generated by `python -m stocklab premarket`; edits here are overwritten) -->"
PM_END = "<!-- PREMARKET:END -->"


def replace_block(text: str, block: str, start: str = START, end: str = END) -> str:
    """Swap the content between the markers; raise if the markers are missing."""
    if start not in text or end not in text:
        raise ValueError(f"README has no generated section; add these two lines where it should go:\n{start}\n{end}")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{block.strip()}\n{end}{tail}"


def write(path: str, block: str, start: str = START, end: str = END) -> None:
    """Update `path` in place, or create a small preview file if it doesn't exist.

    The pre-market section is added right after the board if the README predates it.
    """
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            text = f.read()
    else:
        text = f"# Live board preview\n\n{START}\n{END}\n"
    if start == PM_START and PM_START not in text:
        anchor = END if END in text else None
        if anchor:
            text = text.replace(anchor, f"{anchor}\n\n{PM_START}\n{PM_END}", 1)
        else:
            text += f"\n{PM_START}\n{PM_END}\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(replace_block(text, block, start, end))


def _pct(v, digits=1):
    return "" if pd.isna(v) else f"{v:+.{digits}%}"


def _num(v):
    return "" if pd.isna(v) else f"{v:,.2f}"


def board_table(table: pd.DataFrame) -> str:
    """Compact Markdown table for the README."""
    lines = [
        "| Ticker | Action | Close | 1 day | 1 month | Why | Buy zone (pullback / breakout) | Stop |",
        "|---|---|---:|---:|---:|---|---|---:|",
    ]
    for t, r in table.iterrows():
        action = f"**{r['action']}**" + ("\\*" if r["provisional"] else "")
        can_buy = r["action"] in ("BUY", "HOLD", "WATCH")
        zone = f"{_num(r.get('pullback_entry'))} / {_num(r.get('breakout_trigger'))}" if can_buy and pd.notna(r.get("pullback_entry")) else "—"
        stop = _num(r.get("stop")) if can_buy and pd.notna(r.get("stop")) else "—"
        lines.append(
            f"| {t} | {action} | {_num(r['close'])} | {_pct(r['change_1d'])} | {_pct(r['change_1m'])} | {why(r)} | {zone} | {stop} |"
        )
    return "\n".join(lines)


RULE_WORDS = {"50/200 SMA cross": "the 50/200-day average cross", "Close > 50-day SMA": "holding only above the 50-day average",
              "MACD > signal": "MACD above its signal line", "RSI 30/70": "RSI 30/70",
              "Trailing stop 20%": "a 20% trailing stop", "Volume breakout": "a volume breakout"}


def _count_word(n: int) -> str:
    words = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]
    return words[n] if 0 <= n < len(words) else str(n)


def _rule_item(r) -> str:
    return f"{r.rule} on {r.ticker} ({r.diff:+.2f}, CI [{r.ci_low:+.2f}, {r.ci_high:+.2f}])"


def render_rules(results: pd.DataFrame, counts: dict, chart: str | None, report_path: str, skipped: list | None = None,
                 cost_bps: float = 5) -> str:
    """The rule backtests on the current watchlist: which rules beat holding, and what they did to drawdowns."""
    if results is None or results.empty:
        return ""
    stocks = list(dict.fromkeys(results["ticker"]))
    rules = list(dict.fromkeys(results["rule"]))
    out = ["### Do simple buy/sell rules beat buy & hold?"]
    left_out = f" ({', '.join(skipped)} not yet: too little history)" if skipped else ""
    out.append(
        f"{_count_word(len(rules)).capitalize()} common timing rules ({', '.join(RULE_WORDS.get(x, x) for x in rules)}) "
        f"are backtested on each of the {len(stocks)} watchlist stocks{left_out}, trading at the next close with "
        f"{cost_bps:g} bp costs, and compared with simply holding the stock, using a 95% block-bootstrap confidence "
        "interval for the difference in Sharpe ratio."
    )
    better = results[results["verdict"] == "better"].sort_values("diff", ascending=False)
    worse = results[results["verdict"] == "worse"].sort_values("diff")
    chance = (f"about {counts['expected']:.1f} of each would be expected by chance, so "
              + ("**more rules beat holding than chance explains**." if counts.get("beyond_chance")
                 else "this is **no more than chance alone would produce**: no rule has shown an edge."))
    text = (f"Of {len(results)} rule-by-stock tests, **{len(better)} beat buy & hold** and **{len(worse)} did worse**; "
            f"{chance}")

    def named(df, word):
        if df.empty:
            return ""
        items = [_rule_item(r) for r in df.head(6).itertuples()]
        more = f", and {len(df) - 6} more" if len(df) > 6 else ""
        return f" {word}: " + "; ".join(items) + more + "."

    out.append(text + named(better, "Better") + named(worse, "Worse"))

    by_rule = results.groupby("rule", sort=False).agg(
        better=("verdict", lambda s: int((s == "better").sum())),
        worse=("verdict", lambda s: int((s == "worse").sum())),
        sharpe=("diff", "median"), dd=("dd_change", "median"), time_in=("time_in_market", "median"))
    best_dd = by_rule["dd"].idxmax()
    r = by_rule.loc[best_dd]
    cost = (f"at a median Sharpe cost of {abs(r['sharpe']):.2f}" if r["sharpe"] < 0
            else f"with a median Sharpe change of {r['sharpe']:+.2f}")
    if r["dd"] > 0:
        out.append(f"Where the rules do help is in drawdowns: **{RULE_WORDS.get(best_dd, best_dd)}** "
                   f"made the worst fall shallower by a median {r['dd'] * 100:.0f} percentage points across stocks, {cost}, "
                   f"while in the market {r['time_in']:.0%} of the time.")
    lines = ["| Rule | Beat holding | Did worse | Median Sharpe vs holding | Median change in worst drawdown | Time in market |",
             "|---|---:|---:|---:|---:|---:|"]
    for rule, x in by_rule.iterrows():
        dd = (f"{abs(x['dd']) * 100:.0f} points " + ("shallower" if x["dd"] > 0 else "deeper")) if abs(x["dd"]) >= 0.005 else "about the same"
        lines.append(f"| {rule} | {int(x['better'])} of {len(stocks)} | {int(x['worse'])} of {len(stocks)} | {x['sharpe']:+.2f} | "
                     f"{dd} | {x['time_in']:.0%} |")
    out.append("\n".join(lines))
    if chart:
        out.append(f"![Each rule vs holding the stock]({chart})")
    out.append(f"Per-stock tables with returns, drawdowns and p-values: [`{report_path}`]({report_path}).")
    return "\n\n".join(out)


def render(table, evaluation, findings: dict, as_of: str, source: str, img_dir: str, report_path: str,
           log_info: str | None = None, board_stability: str | None = None, rules_section: str = "") -> str:
    """The full live section: board, legend, evidence and key numbers."""
    out = [f"## Today's board: data as of the {as_of} close"]
    out.append(
        "*Updated automatically after every US trading day by a GitHub Actions workflow. "
        "Labels come from fixed, published rules (see [how labels are chosen](#how-the-board-labels-are-chosen)); "
        "they are not predictions and not investment advice.*"
    )
    if source != "yahoo":
        out.append(f"> **Preview on `{source}` data, not real prices.**")
    out.append(board_table(table))
    if table["provisional"].any():
        out.append(
            "\\* Provisional: listed less than 200 trading days ago, so the trend test uses the 50-day average "
            "and rules that need a longer history are not scored yet."
        )
    legend = "; ".join(f"**{a}**: {ACTIONS[a][1].lower()} if you own it, {ACTIONS[a][2].lower()} if you don't"
                       for a in ("BUY", "HOLD", "WATCH", "AVOID", "REDUCE", "SELL"))
    out.append(f"What each label means: {legend}.")
    out.append(f"![Board label each week]({img_dir}/board_history.png)")

    if evaluation:
        tab = evaluation["table"]
        b, e = tab.loc["Board strategy"], tab.loc["Equal-weight watchlist"]
        test = evaluation.get("sharpe_test")
        verdict = ""
        if test:
            if test["ci_low"] > 0:
                verdict = "better than"
            elif test["ci_high"] < 0:
                verdict = "worse than"
            else:
                verdict = "not distinguishable from"
            verdict = (f" The Sharpe ratio difference is {test['diff']:+.2f} (95% block-bootstrap CI "
                       f"[{test['ci_low']:+.2f}, {test['ci_high']:+.2f}]): **{verdict} simply holding the watchlist**.")
            if board_stability:
                verdict += f" *Stability: {board_stability}.*"
        out.append("### Does the board work?")
        out.append(
            f"Trading the labels since {evaluation['start'].date()} (buy on BUY; exit on SELL, REDUCE or AVOID; "
            f"weekly, next-day execution, 5 bp costs) returned **{b['CAGR']:+.1%} a year** with a worst drawdown of "
            f"{b['Max drawdown']:.1%}, versus {e['CAGR']:+.1%} and {e['Max drawdown']:.1%} for holding every watchlist "
            f"stock in equal weight.{verdict}"
        )
        lab = evaluation["labels"]
        col = [c for c in lab.columns if c.startswith("mean")][0]
        bits = []
        for label in ("BUY", "SELL"):
            if label in lab.index and pd.notna(lab.loc[label, col]):
                r = lab.loc[label]
                bits.append(f"{label} labels were followed by {r[col]:+.1%} versus the watchlist average over 21 days "
                            f"(p = {r['p_value']:.2f}, {int(r['observations'])} observations)")
        if bits:
            out.append("Label by label: " + "; ".join(bits) + ".")
        out.append(f"![Board strategy vs holding]({img_dir}/board_equity.png)")
        out.append(
            "These tests use stocks chosen today, which flatters every long-only strategy (survivorship bias), "
            "so they show whether the labels add anything relative to holding the same stocks, not what to expect in future."
        )

    if rules_section:
        out.append(rules_section)

    if findings:
        out.append("### Key numbers from the latest full report")
        out.append("*Each line ends with how many of the last runs (one per trading day, up to 10) reached the same "
                   "verdict: a result that flips from day to day is sitting on its threshold and is best read as noise.*")
        out.append("\n".join(f"- {line}" for line in findings.values()))
    if log_info:
        out.append(log_info)
    out.append(f"Full tables and charts: [`{report_path}`]({report_path}).")
    return "\n\n".join(out)


LATEST_TITLES = {"pre-market": "Pre-market board", "regular session": "Intraday board",
                 "after-hours": "After-hours board", "closed": "Market closed: board at the latest prices"}
_SESSION_NOTE = {
    "pre-market": "Pre-market trading is thin and prices can move a lot by 9:30 ET.",
    "regular session": "A label at an intraday price is a preview: it can change by the close, and the close-based "
                       "label is the one that has been tested.",
    "after-hours": "After-hours trading is thin.",
}
_COLUMNS = {"pre-market": ("Pre-market label", "Pre-market"), "after-hours": ("After-hours label", "After-hours")}


def render_premarket(v, gaps: dict, gap_text: str, when: str, session: str, source: str, report_path: str,
                     timing_text: str = "") -> str:
    """The board at the latest price: labels with each stock's latest trade as today's price."""
    out = [f"## {LATEST_TITLES.get(session, 'Board at the latest prices')} at {when}"]
    out.append(
        "*The same rules as the board above, with each stock's latest trade standing in for today's close (the "
        "history before it is still daily closes). Prices are Yahoo Finance minute bars, which carry Nasdaq's "
        "real-time last sale and can trail it by a minute or two. Refreshed by GitHub Actions before the US open and "
        "every hour during the session, and whenever `python -m stocklab premarket` is run; `python -m stocklab live` "
        "redraws it every minute in a terminal. " + _SESSION_NOTE.get(session, "") + "*"
    )
    if source != "yahoo":
        out.append(f"> **Preview on `{source}` data, not real prices.**")
    label_col, price_col = _COLUMNS.get(session, ("Label now", "Latest price"))
    lines = [
        f"| Ticker | {label_col} | Board at last close | Last close | {price_col} | Change | Buy zone (pullback / breakout) "
        "| Stop | What the move changes |",
        "|---|---|---|---:|---:|---:|---|---:|---|",
    ]
    for t, r in v.iterrows():
        price = "" if pd.isna(r["price"]) else f"{r['price']:,.2f}"
        name = str(r["premarket_label"]).rstrip("*")
        star = "\\*" if str(r["premarket_label"]).endswith("*") else ""
        label = f"**{name}**{star}" + (" (changed)" if r.get("changed") else "") if name else "—"
        zone = (f"{_num(r.get('pm_pullback_entry'))} / {_num(r.get('pm_breakout'))}"
                if pd.notna(r.get("pm_pullback_entry")) else "—")
        stop = _num(r.get("pm_stop")) if pd.notna(r.get("pm_stop")) else "—"
        lines.append(f"| {t} | {label} | {r['board']} | {_num(r['close'])} | {price} | {_pct(r['change'])} | "
                     f"{zone} | {stop} | {r['crossed'] or '—'} |")
    out.append("\n".join(lines))
    out.append(
        "The two volume rules keep their value from the last close, because a part-day's volume can't be compared "
        "with a full session's, so a label changes here only when the price move switches a price-based rule; the "
        "last column says which. A label marked `*` is provisional (short history). "
        "The close-based board above stays the reference: it is the one with the longer live track record."
    )
    if timing_text:
        out.append("**Does deciding before the open help?** " + timing_text +
                   " The test uses the official opening price as a stand-in for the last pre-market trade, because free "
                   "pre-market history only goes back a few days; every run logs real pre-market labels to "
                   "`reports/premarket_log.csv` for a direct test later.")
    if gap_text:
        out.append("**Do opening gaps carry into the day?** " + gap_text)
    out.append(f"Details: [`{report_path}`]({report_path}).")
    return "\n\n".join(out)
